import asyncio
from harness import *
async def main():
    async with async_playwright() as p:
        b, pg = await setup(p)
        await newproject(pg)
        await pg.click('.doc-table tbody tr >> text=Smith'); await pg.wait_for_timeout(200)
        await pg.screenshot(path=shot('s24-docs.png'))
        await pg.click('.nav >> text=Coding')
        await pg.select_option('.doc-picker', label=await pg.evaluate("[...document.querySelectorAll('.doc-picker option')].find(o=>o.text.startsWith('Smith')).text"))
        await pg.wait_for_selector('.text-layer span', timeout=20000); await pg.wait_for_timeout(400)
        await code(pg, 'insufficient training, large class sizes', ['Barriers'])
        await code(pg, 'Co-teaching arrangements were perceived as particularly effective', ['Collaboration'], occ=3)
        await pg.select_option('.doc-picker', label=await pg.evaluate("[...document.querySelectorAll('.doc-picker option')].find(o=>o.text.startsWith('Rossi')).text"))
        await pg.wait_for_selector('.text-body .block'); await code(pg, 'time constraints and limited resources', ['Barriers'])
        await pg.click('.nav >> text=Review'); await pg.wait_for_timeout(300)
        await pg.click('.card >> nth=1 >> .quote'); await pg.wait_for_timeout(1200)
        await pg.screenshot(path=shot('s25-preview-text.png'))
        await pg.click('.preview .segmented >> text=Pages'); await pg.wait_for_selector('.preview .text-layer span', timeout=15000); await pg.wait_for_timeout(1200)
        await pg.select_option('.preview .zoom', '1.25'); await pg.wait_for_timeout(1200)
        await pg.evaluate("document.querySelector('.preview-host').scrollLeft = 0")
        await pg.screenshot(path=shot('s26-preview-pages.png'))
        print('scrollable width', await pg.evaluate("[document.querySelector('.preview-host').scrollWidth, document.querySelector('.preview-host').clientWidth]"))
        await pg.click('.card:has-text("Co-teaching") .quote'); await pg.wait_for_timeout(1200)
        await pg.screenshot(path=shot('s27-preview-other.png'))
        # edit memo while preview is open
        await pg.click('.card:has-text("Co-teaching") >> text=Edit'); await pg.fill('.editor textarea', 'Mentions co-teaching'); await pg.keyboard.press('Control+Enter'); await pg.wait_for_timeout(300)
        print('preview open after edit:', await pg.evaluate("!document.querySelector('.preview').hidden"), 'active cards', await pg.evaluate("document.querySelectorAll('.card.active').length"))
        await pg.click('.card:has-text("Co-teaching")'); await pg.keyboard.press('Escape'); await pg.wait_for_timeout(200)
        print('preview hidden after Esc:', await pg.evaluate("document.querySelector('.preview').hidden"))
        await pg.click('.card:has-text("time constraints") .quote'); await pg.wait_for_timeout(800)
        await pg.screenshot(path=shot('s28-preview-docx.png'))
        print('ERRORS', errors)
        await b.close()
asyncio.run(main())
